from __future__ import annotations

import logging
import shutil
from pathlib import Path
from typing import Any, Dict, List

from src.data.xml_utils import load_detection_records, parse_voc_xml

logger = logging.getLogger(__name__)


def _voc_to_yolo(
    xmin: int,
    ymin: int,
    xmax: int,
    ymax: int,
    img_w: int,
    img_h: int,
) -> tuple[float, float, float, float]:

    cx = ((xmin + xmax) / 2.0) / img_w
    cy = ((ymin + ymax) / 2.0) / img_h
    w = (xmax - xmin) / img_w
    h = (ymax - ymin) / img_h

    return cx, cy, w, h


def convert_rdd_to_yolo(
    cfg: Dict[str, Any], out_dir: str | Path = "yolo_dataset"
) -> Path:

    out_dir = Path(out_dir)
    dataset_yaml = out_dir / "dataset.yaml"

    if dataset_yaml.exists():
        logger.info(
            "[yolo] Dataset already exists at %s — skipping conversion.", out_dir
        )
        return dataset_yaml

    data_cfg = cfg["data"]
    rdd_root = data_cfg["rdd_root"]
    allowed = data_cfg["allowed_labels"]
    label_map = {lab: i for i, lab in enumerate(allowed)}

    common = dict(
        rdd_root=rdd_root,
        allowed_labels=allowed,
        countries=data_cfg.get("countries"),
        split_mode=data_cfg.get("split_mode", "random"),
        train_ratio=data_cfg.get("train_ratio", 0.8),
        val_ratio=data_cfg.get("val_ratio", 0.1),
        seed=cfg.get("seed", 1337),
        xml_glob=data_cfg.get("xml_glob", "**/annotations/xmls/*.xml"),
        image_dir_hint=data_cfg.get("image_dir_hint", "images"),
    )

    for split in ("train", "val"):
        logger.info("[yolo] Converting %s split ...", split)
        records = load_detection_records(split=split, **common)

        img_out = out_dir / "images" / split
        lbl_out = out_dir / "labels" / split
        img_out.mkdir(parents=True, exist_ok=True)
        lbl_out.mkdir(parents=True, exist_ok=True)

        for rec in records:
            src_img = Path(rec["image_path"])
            ann_path = rec["ann_path"]

            img_w, img_h, objects = parse_voc_xml(ann_path)

            lines: List[str] = []
            for label_str, (xmin, ymin, xmax, ymax) in objects:
                if label_str not in label_map:
                    continue
                cls_id = label_map[label_str]
                cx, cy, w, h = _voc_to_yolo(xmin, ymin, xmax, ymax, img_w, img_h)
                cx = max(0.0, min(1.0, cx))
                cy = max(0.0, min(1.0, cy))
                w = max(0.0, min(1.0, w))
                h = max(0.0, min(1.0, h))
                lines.append(f"{cls_id} {cx:.6f} {cy:.6f} {w:.6f} {h:.6f}")

            if not lines:
                continue

            # copy image
            dst_img = img_out / src_img.name
            if not dst_img.exists():
                shutil.copy2(src_img, dst_img)

            # write label file
            lbl_file = lbl_out / (src_img.stem + ".txt")
            lbl_file.write_text("\n".join(lines))

        n_written = len(list(lbl_out.glob("*.txt")))
        logger.info("[yolo]   %s: %s images written", split, n_written)

    names_str = "\n".join(f"{lab}," for lab in allowed)
    yaml_content = (
        "# Auto-generated by dataset_yolo.py\n"
        f"path: {out_dir.resolve()}\n"
        "train: images/train\n"
        "val:   images/val\n"
        "\n"
        f"nc: {len(allowed)}\n"
        "names:\n"
        f"[{names_str}]\n"
    )

    dataset_yaml.write_text(yaml_content)
    logger.info("[yolo] dataset.yaml written to %s", dataset_yaml)

    return dataset_yaml
